// Spike: `claude --remote-control` inside a SessionDeck pty: footer text, "working" marker, and resume keeps RC.
const lib = require('../e2e-lib.cjs')
const tail = async (app, id, n) => lib.strip((await app.evaluate(`window.api.ptyReplay(${JSON.stringify(id)})`)).data).slice(-n)
;(async () => {
  const app = await lib.launchApp({ port: 9397 })
  await lib.sleep(1500)
  const s = await app.evaluate(`window.api.createSession({ cwd: ${JSON.stringify(lib.ROOT)}, name: 'rc probe', claudeArgs: ['--remote-control', 'sd-rc-probe'] })`)
  const id = JSON.stringify(s.id)
  await lib.sleep(1500)
  await app.evaluate(`[...document.querySelectorAll('[role="treeitem"]')].find((n) => n.innerText.includes('rc probe')).click()`)
  await lib.waitFor(async () => /Try "|❯/.test(await tail(app, s.id, 3000)), 40000, 1000)
  await lib.sleep(4000)
  console.log('--- idle footer:', JSON.stringify((await tail(app, s.id, 600))))
  await app.evaluate(`window.api.ptyWrite(${id}, 'run the shell command: ping -n 6 127.0.0.1 and then say done')`)
  await lib.sleep(400)
  await app.evaluate(`window.api.ptyWrite(${id}, '\\r')`)
  await lib.sleep(5000)
  const mid = await tail(app, s.id, 1500)
  console.log('--- working has "esc to interrupt":', /esc\s*to\s*interrupt/i.test(mid))
  console.log(JSON.stringify(mid.slice(-500)))
  await lib.sleep(15000)
  // sleep + wake: does the resumed process come back with remote control?
  await app.evaluate(`window.api.createSession({ cwd: ${JSON.stringify(lib.ROOT)}, name: 'other' })`)
  await lib.sleep(2000)
  await app.evaluate(`[...document.querySelectorAll('[role="treeitem"]')].find((n) => n.innerText.includes('other')).click()`)
  await lib.sleep(800)
  await app.evaluate(`window.api.sleepSession(${id})`)
  await lib.sleep(2500)
  await app.evaluate(`[...document.querySelectorAll('[role="treeitem"]')].find((n) => n.innerText.includes('rc probe')).click()`)
  await lib.sleep(20000)
  const after = await tail(app, s.id, 1200)
  console.log('--- after wake, rc active:', /\/rc\s*active|remote-control is active/i.test(after))
  console.log(JSON.stringify(after.slice(-400)))
  app.kill()
})()
