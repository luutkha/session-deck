const lib = require('../e2e-lib.cjs')
;(async () => {
  const app = await lib.launchApp({ port: 9399 })
  await lib.sleep(1500)
  await app.evaluate(`window.api.createSession({ cwd: ${JSON.stringify(lib.ROOT)}, name: 'auto probe' })`)
  await app.evaluate(`window.api.createSession({ cwd: ${JSON.stringify(lib.ROOT)}, name: 'second pane' })`)
  await lib.sleep(2500)
  const click = (n) => app.evaluate(`[...document.querySelectorAll('[role="treeitem"]')].find((x) => x.innerText.trim().startsWith('${n}')).click()`)
  await click('second pane'); await lib.sleep(1200); await click('auto probe'); await lib.sleep(1200)
  const r = await app.evaluate(`(() => { const b = document.querySelector('[aria-label="Split view"]'); if (!b) return 'no button'; const r = b.getBoundingClientRect(); return JSON.stringify({ x: r.left + r.width / 2, y: r.top + r.height / 2, disabled: b.disabled, tabs: document.querySelectorAll('[role=tab]').length }) })()`)
  console.log('button', r)
  const c = JSON.parse(r)
  await app.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x: c.x, y: c.y, button: 'none' })
  await app.send('Input.dispatchMouseEvent', { type: 'mousePressed', x: c.x, y: c.y, button: 'left', buttons: 1, clickCount: 1 })
  await app.send('Input.dispatchMouseEvent', { type: 'mouseReleased', x: c.x, y: c.y, button: 'left', buttons: 1, clickCount: 1 })
  await lib.sleep(800)
  console.log('menu', await app.evaluate(`JSON.stringify([...document.querySelectorAll('[role=menuitem]')].map((n) => n.innerText + (n.getAttribute('aria-disabled') ? '(disabled)' : '')))`))
  app.kill()
})()
